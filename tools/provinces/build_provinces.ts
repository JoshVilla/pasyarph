// Builds tools/provinces/out/provinces.sql (insert statements for
// public.provinces) from geoBoundaries' Philippines ADM2 (provinces)
// GeoJSON. See README.md.
//
// Usage: deno run --allow-read --allow-write tools/provinces/build_provinces.ts <adm2.geojson>

type Ring = [number, number][];
type Polygon = Ring[];

/** Boundary detail kept: points closer than this to the simplified line go.
 * Province lookups only need to be right away from the borders. */
const TOLERANCE_M = 250;

/** Display names: Metro Manila instead of its four districts, current
 * province names, and independent cities under the province around them. */
const RENAME: Record<string, string> = {
  'NCR, City of Manila, First District': 'Metro Manila',
  'NCR, Second District': 'Metro Manila',
  'NCR, Third District': 'Metro Manila',
  'NCR, Fourth District': 'Metro Manila',
  'Compostela Valley': 'Davao de Oro',
  'City of Isabela': 'Basilan',
  'Cotabato City': 'Maguindanao',
};

const M_PER_DEG = 111_320;

/** Douglas–Peucker in local meters (longitude scaled by cos latitude). */
function simplify(ring: Ring, toleranceM: number): Ring {
  if (ring.length <= 4) return ring;
  const k = Math.cos((ring[0][1] * Math.PI) / 180) * M_PER_DEG;
  const pts = ring.map(([x, y]) => [x * k, y * M_PER_DEG]);
  const keep = new Uint8Array(ring.length);
  keep[0] = keep[ring.length - 1] = 1;
  const stack: [number, number][] = [[0, ring.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop()!;
    const [ax, ay] = pts[a];
    const [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay;
    const len2 = dx * dx + dy * dy;
    let worst = -1, worstD = toleranceM;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = pts[i];
      const t = len2 === 0
        ? 0
        : Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / len2));
      const d = Math.hypot(px - (ax + t * dx), py - (ay + t * dy));
      if (d > worstD) {
        worstD = d;
        worst = i;
      }
    }
    if (worst >= 0) {
      keep[worst] = 1;
      stack.push([a, worst], [worst, b]);
    }
  }
  return ring.filter((_, i) => keep[i]);
}

const round = (v: number) => Math.round(v * 1e5) / 1e5;

function cleanPolygon(poly: Polygon): Polygon | null {
  const ring = (r: Ring) =>
    simplify(r, TOLERANCE_M).map(([x, y]) => [round(x), round(y)] as [number, number]);
  const outer = ring(poly[0]);
  // An islet smaller than the tolerance: nothing left to keep.
  if (outer.length < 4) return null;
  const holes = poly.slice(1).map(ring).filter((r) => r.length >= 4);
  return [outer, ...holes];
}

const path = Deno.args[0];
if (!path) {
  console.error('Usage: build_provinces.ts <geoBoundaries-PHL-ADM2.geojson>');
  Deno.exit(1);
}

// deno-lint-ignore no-explicit-any
const geojson = JSON.parse(await Deno.readTextFile(path)) as any;
const byName = new Map<string, Polygon[]>();
for (const f of geojson.features) {
  const raw = String(f.properties.shapeName);
  const name = RENAME[raw] ?? raw;
  const polys: Polygon[] = f.geometry.type === 'Polygon'
    ? [f.geometry.coordinates]
    : f.geometry.coordinates;
  const kept = polys.map(cleanPolygon).filter((p): p is Polygon => p !== null);
  byName.set(name, [...(byName.get(name) ?? []), ...kept]);
}

const lines = [
  '-- Generated by tools/provinces/build_provinces.ts from geoBoundaries',
  '-- PHL ADM2 (NAMRIA / PSA / OCHA, CC BY 3.0 IGO). Run after',
  '-- 20261019000400_provinces.sql. Replaces all rows.',
  'begin;',
  'truncate public.provinces;',
];
let points = 0;
for (const [name, polys] of [...byName].sort(([a], [b]) => a.localeCompare(b))) {
  const geometry = JSON.stringify({ type: 'MultiPolygon', coordinates: polys });
  points += polys.flat(2).length;
  lines.push(
    `insert into public.provinces (name, area) values ('${name.replaceAll("'", "''")}', ` +
      `extensions.st_multi(extensions.st_collectionextract(extensions.st_makevalid(extensions.st_setsrid(extensions.st_geomfromgeojson('${geometry}'), 4326)), 3))::extensions.geography);`,
  );
}
lines.push(
  '-- Loops saved before provinces were loaded.',
  'update public.loops set province = public.loop_province(route, main_stop);',
  'commit;',
  '',
);

await Deno.mkdir(new URL('./out/', import.meta.url), { recursive: true });
const out = new URL('./out/provinces.sql', import.meta.url);
await Deno.writeTextFile(out, lines.join('\n'));
const size = (await Deno.stat(out)).size;
console.log(
  `${byName.size} provinces, ${points} points, ${(size / 1024).toFixed(0)} KB -> ${out.pathname}`,
);
